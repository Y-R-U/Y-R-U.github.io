#!/usr/bin/env node
// Co-credits (two directors, two authors): questions ask about the best-known one only. Fame = credits across the
// film/book/invention packs, ties to the first listed. Writes js/formats/cocredit_data.js (only people who share a
// credit, so it stays small). Rerun after the screen/books packs change: node tools/trio_cocredit.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const { CREDIT_KEYS, people } = await import(new URL('../js/formats/cocredit.js', import.meta.url).href);
const SOURCES = { movies: ['director'], 'movie-moments': ['director'], books: ['author'], inventions: ['inventor'] };
const norm = s => s.trim().toLowerCase();
const count = new Map(), shared = new Set();
for (const [id, keys] of Object.entries(SOURCES)) {
  const pack = JSON.parse(readFileSync(join(ROOT, 'data/packs', `${id}.json`), 'utf8'));
  for (const k of keys) {
    if (!CREDIT_KEYS.has(k)) throw new Error(`${k} is not in CREDIT_KEYS`);
    // the same film in two packs counts once
    const seen = new Set();
    for (const it of pack.items) {
      const ps = people(it.facts?.[k]);
      const key = `${norm(it.name)}|${ps.map(norm).sort().join('|')}`;
      if (seen.has(key)) continue;
      seen.add(key);
      for (const p of ps) count.set(norm(p), (count.get(norm(p)) || 0) + 1);
      if (ps.length > 1) ps.forEach(p => shared.add(norm(p)));
    }
  }
}
const out = Object.fromEntries([...shared].sort().map(p => [p, count.get(p)]));
writeFileSync(join(ROOT, 'js/formats/cocredit_data.js'),
  `// Generated by tools/trio_cocredit.mjs: credits per person who shares a credit (lower-case name → films/books).\nexport default ${JSON.stringify(out)};\n`);
console.log(`cocredit: ${shared.size} people share credits; top: ${Object.entries(out).sort((a, b) => b[1] - a[1]).slice(0, 8).map(([p, n]) => `${p} ${n}`).join(', ')}`);
