#!/usr/bin/env node
// Writes js/formats/series_data.js: item id -> series, so options from one film franchise or book series count as
// look-alikes (easy: never two from one series; medium: one pair at most; hard: offered first). Films use
// movies.json's franchise fact; books use the list below. Rerun after the movies or books packs change.
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const pack = id => JSON.parse(readFileSync(join(ROOT, 'data/packs', id + '.json'), 'utf8'));
const BOOKS = {
  'Harry Potter': /^Harry Potter and/,
  'The Hunger Games': /^(The Hunger Games|Catching Fire|Mockingjay)$/,
  'Middle-earth': /^(The Hobbit|The Lord of the Rings)$/,
  'Alice': /^(Alice's Adventures in Wonderland|Through the Looking-Glass)$/,
  'Sherlock Holmes': /^(The Hound of the Baskervilles|A Study in Scarlet|The Adventures of Sherlock Holmes)$/,
  'Hercule Poirot': /^(Murder on the Orient Express|The Murder of Roger Ackroyd|Death on the Nile)$/,
  'Tom Sawyer': /^(The Adventures of Tom Sawyer|Adventures of Huckleberry Finn)$/,
  'Narnia': /^The (Lion, the Witch and the Wardrobe|Magician's Nephew|Voyage of the Dawn Treader)/,
  'Twilight': /^(Twilight|New Moon|Eclipse|Breaking Dawn)$/,
};
const out = {};
const films = pack('movies');
for (const it of films.items) if (it.facts?.franchise) out[it.id] = it.facts.franchise;
for (const id of ['movie-moments', 'tv']) {
  try { for (const it of pack(id).items) if (!out[it.id]) { const f = films.items.find(m => m.id === it.id || m.name === it.name); if (f?.facts?.franchise) out[it.id] = f.facts.franchise; } } catch (e) { /* optional pack */ }
}
for (const id of ['books', 'book-moments']) {
  try { for (const it of pack(id).items) for (const [s, re] of Object.entries(BOOKS)) if (re.test(it.name)) out[it.id] = s; } catch (e) { /* optional pack */ }
}
const keys = Object.keys(out).sort();
writeFileSync(join(ROOT, 'js/formats/series_data.js'),
  '// Generated by tools/series_build.mjs: item id -> film franchise or book series.\nexport const SERIES = ' +
  JSON.stringify(Object.fromEntries(keys.map(k => [k, out[k]])), null, 0).replace(/","/g, '",\n"').replace(/^{/, '{\n').replace(/}$/, '\n}') + ';\n');
const n = {};
for (const s of Object.values(out)) n[s] = (n[s] || 0) + 1;
console.log(`${keys.length} items in ${Object.keys(n).length} series; book series:`, Object.keys(BOOKS).map(s => `${s} ${n[s] || 0}`).join(', '));
