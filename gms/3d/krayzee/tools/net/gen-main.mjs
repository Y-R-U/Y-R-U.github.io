// Builds tools/net/gen/{index.html,main.js}: today's js/main.js with the docs/ONLINE.md §15 wiring block applied, so the
// two-window test runs the real game without editing js/main.js. Every anchor must match or this throws.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('../../', import.meta.url));
const OUT = fileURLToPath(new URL('./gen/', import.meta.url));

export const PATCHES = [
  ['let net = null, lobby = null;', 'let net = null, lobby = null, session = null;'],
  [
    `      const [{ createNet }, { createLobby }] = await Promise.all([import('./net/index.js'), import('./net/lobby.js')]);
      net = createNet({ profile: () => ui.getProfile(), getToken: null });
      lobby = createLobby({ net, profile: () => ui.getProfile(), onStart: () => { lobby.show(false); ui.enterGameplay(); onPlay('online'); }, onClose: () => ui.showMenu() });`,
    `      const [{ createNet, accountToken }, { createLobby }, { createSession }] = await Promise.all([import('./net/index.js'), import('./net/lobby.js'), import('./net/session.js')]);
      net = createNet({ profile: () => ui.getProfile(), getToken: accountToken });
      session = createSession({ net, scene, traffic, wiring, attract, createPlane, applyEnv, env, career, ui, hud, fx, log,
        onExit: () => { quitPlay(); ui.showMenu(); lobby.show(true); } });
      lobby = createLobby({ net, profile: () => ui.getProfile(), onStart: async () => { lobby.show(false); ui.enterGameplay(); await onPlay('online'); if (S.player) session.attach(S.player); }, onClose: () => ui.showMenu() });`,
  ],
  [
    `  if (net) try { net.tick(performance.now(), { ready: gov.fps > 40, parked: !P || (P.ac.onGround && P.ac.gs < 1) }); } catch (e) { /* */ }`,
    `  if (net) try { net.tick(performance.now(), { ready: gov.fps > 40, parked: !P || (P.ac.onGround && P.ac.gs < 1) }); } catch (e) { /* */ }
  if (session) try { session.update(dt); } catch (e) { console.warn('[net]', e); }`,
  ],
  [`function quitPlay() {
  if (!S.player) return;`, `function quitPlay() {
  if (!S.player) return;
  session?.detach();`],
  ['function onQuit() { quitPlay();', 'function onQuit() { session?.detach({ leave: true }); quitPlay();'],
];

export function build() {
  let main = readFileSync(ROOT + 'js/main.js', 'utf8');
  for (const [a, b] of PATCHES) {
    if (main.includes(b)) continue;
    if (!main.includes(a)) throw new Error(`gen-main: anchor not found in js/main.js:\n${a.slice(0, 160)}`);
    main = main.replace(a, b);
  }
  main = main.replace(/(from\s+|import\()'\.\//g, "$1'../../../js/");
  main += '\n// test hook (generated copy only)\nwindow.__krzNet = { get net() { return net; }, get session() { return session; }, get lobby() { return lobby; }, get attract() { return attract; } };\n';
  let html = readFileSync(ROOT + 'index.html', 'utf8');
  html = html.replace('<head>', '<head>\n<base href="/gms/3d/krayzee/">').replace('src="js/main.js"', 'src="tools/net/gen/main.js"');
  mkdirSync(OUT, { recursive: true });
  writeFileSync(OUT + 'main.js', `// GENERATED by tools/net/gen-main.mjs from js/main.js + the ONLINE §15 wiring. Do not edit.\n${main}`);
  writeFileSync(OUT + 'index.html', html);
  return OUT;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) console.log(build());
