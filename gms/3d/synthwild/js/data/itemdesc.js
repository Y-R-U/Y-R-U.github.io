const TOOL_DESC = {
  cutter: 'Mines stone and ore fast.',
  saw: 'Chops wood fast. Fells whole trees!',
  scoop: 'Digs soil, sand and gravel fast.',
  blade: 'A weapon. Hits monsters hard.',
};
const TIER_WORD = { lattice: 'Starter', basalt: 'Stone-tough', ferrite: 'Metal', qubit: 'The best' };

export function descFor(it) {
  if (DESC[it.key]) return DESC[it.key];
  if (it.tool && TOOL_DESC[it.tool.type]) return `${TIER_WORD[it.tool.tier] || ''} tier. ${TOOL_DESC[it.tool.type]}`.trim();
  return it.desc || (it.kind === 'block' ? 'A building block.' : '');
}
