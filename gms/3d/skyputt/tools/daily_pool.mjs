#!/usr/bin/env node
// The online boards' view of the courses (boards agent, docs/notes/boards.md).
//
// The server verifies a daily submission by recomputing the day's hole + twist in Go
// (server/daily.go, a port of js/daily/daily.js). It needs the hole list, so this tool writes it
// from the real JS course data, plus a fixture of JS picks the Go test compares against:
//
//   node tools/daily_pool.mjs           write server/dailypool.json + server/testdata/daily_picks.json
//   node tools/daily_pool.mjs --check   exit 1 if either file is stale (tools/boards_test.mjs runs this)
//
// RULE: after adding / changing a course, a hole's par or crystals, a theme, or a `dailyFrom`,
// run this, rerun server/test.sh, and redeploy the server, or the server will refuse daily
// results on the days the change affects (the client then just hides its own row; nothing breaks).
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const mem = new Map();
globalThis.localStorage = { getItem: k => (mem.has(k) ? mem.get(k) : null), setItem: (k, v) => mem.set(k, String(v)), removeItem: k => mem.delete(k) };
const { COURSES } = await import('../js/course/holes/index.js');
const { THEME_LIST } = await import('../js/app/menus.js');
const { themeIds, addDays } = await import('../js/events/calendar.js');
const { dailyFor, DAILY_EPOCH, TWISTS } = await import('../js/daily/daily.js');

const HERE = dirname(fileURLToPath(import.meta.url));
const POOL = join(HERE, '../server/dailypool.json');
const PICKS = join(HERE, '../server/testdata/daily_picks.json');
export const PICK_DAYS = 460;   // from DAILY_EPOCH: covers reef's dailyFrom (2026-11-16) and a year+ beyond

const pickups = h => (h.features || []).filter(f => f.type === 'pickup').length;
export function pool() {
  return {
    note: 'Generated by tools/daily_pool.mjs from js/course/holes + js/app/menus.js. Do not edit by hand.',
    epoch: DAILY_EPOCH,
    twists: TWISTS.map(t => t.id),
    courses: Object.values(COURSES).map(c => ({
      id: c.id, name: c.name, locked: !!c.lockedBy, ...(c.dailyFrom ? { dailyFrom: c.dailyFrom } : {}),
      nines: (c.nines || []).map(n => ({ id: n.id, name: n.name, from: n.from, to: n.to })),
      holes: c.holes.map(h => ({ id: h.id, par: h.par, pickups: pickups(h) })),
    })),
    themes: themeIds().map(id => { const t = THEME_LIST.find(x => x.id === id); return { id, ...(t?.dailyFrom ? { dailyFrom: t.dailyFrom } : {}) }; }),
  };
}

// Every subset of the lockable courses (a player's open set), as the sorted list of OPEN lockable ids.
export function openSets() {
  const L = Object.values(COURSES).filter(c => c.lockedBy).map(c => c.id);
  return Array.from({ length: 1 << L.length }, (_, m) => L.filter((_, i) => m & (1 << i)));
}

// JS picks: per day the global pick, plus per open set only the days where it differs.
export function picks(days = PICK_DAYS) {
  const lockable = new Set(Object.values(COURSES).filter(c => c.lockedBy).map(c => c.id));
  const out = { from: DAILY_EPOCH, days, global: [], sets: {} };
  for (let i = 0; i < days; i++) {
    const d = addDays(DAILY_EPOCH, i), g = dailyFor(d);
    out.global.push(`${g.hole.id} ${g.twist.id} ${g.theme}`);
  }
  for (const set of openSets()) {
    if (set.length === lockable.size) continue;
    const key = set.join(',') || '-', open = c => !lockable.has(c.id) || set.includes(c.id), diff = {};
    for (let i = 0; i < days; i++) {
      const d = addDays(DAILY_EPOCH, i), ch = dailyFor(d, { open });
      const s = `${ch.hole.id} ${ch.twist.id}`;
      if (!out.global[i].startsWith(s + ' ')) diff[d] = s;
    }
    out.sets[key] = diff;
  }
  return out;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const want = { [POOL]: JSON.stringify(pool(), null, 1) + '\n', [PICKS]: JSON.stringify(picks()) + '\n' };
  if (process.argv.includes('--check')) {
    let stale = 0;
    for (const [f, s] of Object.entries(want)) {
      let have = ''; try { have = readFileSync(f, 'utf8'); } catch { /* missing */ }
      if (have !== s) { stale++; console.log(`STALE ${f} — run node tools/daily_pool.mjs`); }
    }
    if (!stale) console.log('dailypool.json + daily_picks.json match the JS');
    process.exit(stale ? 1 : 0);
  }
  mkdirSync(dirname(PICKS), { recursive: true });
  for (const [f, s] of Object.entries(want)) { writeFileSync(f, s); console.log('wrote', f, s.length, 'bytes'); }
}
