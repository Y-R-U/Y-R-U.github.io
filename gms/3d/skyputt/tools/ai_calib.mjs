#!/usr/bin/env node
// Turns an ai_test JSON dump into js/ai/calib.js: per hole, per personality, per skill, a histogram
// of strokes (index 0 = 1 stroke ... par+4), used by simulateRound's quick mode.
//   node tools/ai_test.mjs --rounds=20 --skills=0.1,0.3,0.5,0.7,1 --json=/tmp/ai.json && node tools/ai_calib.mjs /tmp/ai.json
//   --merge keeps the holes already in js/ai/calib.js that the new JSON doesn't cover (e.g. calibrate only
//   the back nine: ai_test --holes=sky10,...,sky18, then ai_calib FILE --merge). Skills and rounds must match.
import { readFileSync, writeFileSync } from 'node:fs';
import { COURSES } from '../js/course/holes/index.js';
const src = process.argv.slice(2).find(a => !a.startsWith('--'));
const MERGE = process.argv.includes('--merge');
if (!src) { console.error('usage: node tools/ai_calib.mjs <ai_test.json>'); process.exit(1); }
const res = JSON.parse(readFileSync(src, 'utf8'));
const skills = [...new Set(res.map(r => r.skill))].sort((a, b) => a - b);
const pids = [...new Set(res.map(r => r.pid))];
const holes = Object.keys(res[0].perHole);
const pars = {};
for (const c of Object.values(COURSES)) for (const h of c.holes) pars[h.id] = h.par;
const out = { skills, pars, holes: {}, n: res[0].strokes.length, made: new Date().toISOString().slice(0, 10) };
for (const h of holes) {
  out.holes[h] = {};
  for (const p of pids) out.holes[h][p] = skills.map(sk => {
    const r = res.find(x => x.pid === p && x.skill === sk);
    const hist = new Array(8).fill(0);
    for (const s of r.perHole[h]) hist[Math.min(7, s - 1)]++;
    return hist;
  });
}
if (MERGE) {
  const { CALIB: old } = await import(new URL('../js/ai/calib.js', import.meta.url));
  if (JSON.stringify(old.skills) !== JSON.stringify(out.skills) || old.n !== out.n) { console.error('merge: skills / rounds differ from js/ai/calib.js'); process.exit(1); }
  for (const [h, v] of Object.entries(old.holes)) if (!out.holes[h]) out.holes[h] = v;
  out.holes = Object.fromEntries(Object.keys(pars).filter(h => out.holes[h]).map(h => [h, out.holes[h]]));
}
const body = `// GENERATED by tools/ai_calib.mjs from tools/ai_test.mjs (${out.n} rounds per cell, ${out.made}). Do not edit.
// Quick-mode stroke histograms: CALIB.holes[holeId][personality][skillIndex][strokes - 1] = count.
export const CALIB = ${JSON.stringify(out)};
`;
writeFileSync(new URL('../js/ai/calib.js', import.meta.url), body);
console.log(`wrote js/ai/calib.js: ${Object.keys(out.holes).length} holes x ${pids.length} personalities x ${skills.length} skills`);
