// node js/audio/gen_manifest.mjs  ->  rewrites js/audio/manifest.js from what is actually in audio/music + audio/sfx.
// Run it after adding or removing any audio file: the engine only ever fetches files listed in the manifest.
import { readdirSync, statSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';

const here = fileURLToPath(new URL('.', import.meta.url));
const root = join(here, '../../audio');
const files = {};
for (const dir of ['music', 'sfx']) {
  let names = [];
  try { names = readdirSync(join(root, dir)); } catch (e) { continue; }
  for (const n of names.sort()) if (/\.(mp3|m4a|ogg|wav)$/.test(n)) files[`${dir}/${n}`] = statSync(join(root, dir, n)).size;
}
const body = Object.entries(files).map(([k, v]) => `  '${k}': ${v},`).join('\n');
writeFileSync(join(here, 'manifest.js'),
  `// GENERATED by gen_manifest.mjs: audio files that ship (path under audio/ -> bytes). Do not edit by hand.\nexport const FILES = {\n${body}\n};\n`);
console.log(Object.keys(files).length, 'files,', (Object.values(files).reduce((a, b) => a + b, 0) / 1e6).toFixed(2), 'MB');
