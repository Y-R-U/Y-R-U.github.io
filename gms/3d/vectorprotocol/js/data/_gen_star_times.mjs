// node js/data/_gen_star_times.mjs → js/data/star_times.js
// Time-goal limit per story level: a mirror of the level's biggest wave, levelled to RATIO × the
// level's power, fights it on 12 seeds; limit = median win time × SLACK rounded up to 5 s.
// Levels where that squad can't win reliably get null (maps.js then uses a different goal).
// Re-run after changing waves, unit stats or rules.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { loadData } from '../sim/data.js';
import { simulateBattle, autoSlots } from '../sim/battle.js';
import { squadPower } from '../sim/stats.js';
import { allLevels } from '../sim/story.js';
import { SLOT_UNLOCKS } from './maps.js';

const RATIO = 1.3, SLACK = 0.95, SEEDS = 12;
const D = await loadData();
const CAPS = [10, 20, 30, 40, 50, 60];
const START = { common: 0, rare: 1, epic: 2, legendary: 3 };
const rankFor = (r, lv) => { let k = START[r] ?? 0; while (k < 5 && CAPS[k] < lv) k++; return k; };
const slotAfter = Object.fromEntries(Object.entries(SLOT_UNLOCKS).map(([s, id]) => [id, +s]));
const out = {};
let slots = D.economy?.start?.slots || 2;
for (const l of allLevels(D)) {
  const strip = (d) => d.replace(/_elite$/, '');
  const notBoss = (d) => !D.enemies?.[d]?.boss;
  const big = l.waves.reduce((a, w) => (w.units.length >= a.units.length ? w : a));
  const pool = [...new Set(l.waves.flatMap((w) => w.units.map((u) => strip(u.def))).filter(notBoss))];
  let defs = big.units.map((u) => strip(u.def)).filter(notBoss);
  while (defs.length < slots && pool.length) defs.push(pool[defs.length % pool.length]);
  defs = defs.slice(0, slots);
  const mk = (lv) => autoSlots(D, defs.map((d) => ({ def: d, level: lv, rank: rankFor((D.units[d] || D.enemies[d]).rarity, lv), abilityLevels: { attack: 3, passive: 3, overdrive: 3 } })));
  let sq = mk(1);
  for (let lv = 1; lv <= 70; lv++) { sq = mk(lv); if (squadPower(D, sq) >= l.power * RATIO) break; }
  const times = [];
  for (let s = 1; s <= SEEDS; s++) { const r = simulateBattle({ data: D, player: { units: sq }, enemyWaves: l.waves, seed: s * 977 }); if (r.win) times.push(r.time); }
  times.sort((a, b) => a - b);
  out[l.id] = times.length >= SEEDS / 2 ? Math.max(10, Math.ceil((times[Math.floor(times.length / 2)] * SLACK) / 5) * 5) : null;
  if (slotAfter[l.id]) slots = slotAfter[l.id];
}
const body = Object.entries(out).map(([k, v]) => `${k}: ${v}`).join(', ').replace(/(([^,]*,){8})/g, '$1\n ');
const file = fileURLToPath(new URL('./star_times.js', import.meta.url));
writeFileSync(file, `// GENERATED by node js/data/_gen_star_times.mjs — do not hand-edit. Time-goal limits (s) per level.\nexport const STAR_TIMES = {\n ${body}\n};\nexport default STAR_TIMES;\n`);
console.log(`wrote ${file}: ${Object.values(out).filter((v) => v).length}/${Object.keys(out).length} levels with a time limit`);
